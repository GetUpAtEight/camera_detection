"""低频稀疏采样（1 小时 / 1 天一次拉帧）篡改检测。

与 ``detectors/`` 下那批"实时逐帧"算法不同，本包面向的是：

* **采样周期很稀疏**（默认 1 小时一次），相邻样本之间没有帧间连续性；
* **单次抽样可能连拉 K 帧**（K≈3~5，帧间隔 0.5~2 秒），形成一个几秒长的"微时序"；
* **历史样本可以攒**，因此可以把"上一次采样"扩展成"同一机位的历史基线库"。

三层信号模型（全包的骨架）：

===========  ======================  ==========================================
层            时间尺度                 能判什么
===========  ======================  ==========================================
``L0``       相邻采样点间隔 1h~1d     与历史基线的偏离（持续篡改、渐变、时序异常）
``L1``       单次抽样内部 K 帧（秒级） 冻结/重放、物理扰动、曝光稳定性、样本质量门控
``L2``       任意单帧                 画质退化（失焦、遮挡）与物理一致性
===========  ======================  ==========================================

核心判据（对应 ``docs/research/00-FINAL-REPORT.md``）：

1. **冻结/重放**：bit-exact + 噪声残差 σ + 运动×噪声 2×2 象限；
2. **稳定性分解**：``d_hist``（历史偏离）× ``d_burst``（微时序动态）构成 4 格矩阵；
3. **按槽中位数背景**：以同时段历史样本的中位数作为参考，逐像素鲁棒 z-score。

公开入口
--------

* :class:`sparse.engine.SparseEngine` —— 一次采样的完整判定流程；
* :class:`sparse.store.CameraStore` —— 机位状态与基线库的落盘持久化。
"""

